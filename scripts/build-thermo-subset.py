#!/usr/bin/env python3
"""Build crates/astraea-core/data/thermo-propellant.inp from NASA CEA thermo.inp.

Usage: python3 scripts/build-thermo-subset.py <path/to/thermo.inp>

Source: NASA Glenn thermodynamic database (McBride, Zehe & Gordon,
NASA/TP-2002-211556), as distributed with NASA CEA (e.g. the copy shipped in
the RocketCEA package). Records are copied verbatim (NASA-9 format); only
species made of propellant-relevant elements are kept, and ions are dropped
(CEA leaves ions out unless asked).
"""
import sys

KEEP = {"C", "H", "O", "N", "CL", "AL", "K", "NA", "MG", "S", "F", "FE",
        "CA", "B", "LI", "SR", "BA", "TI", "CU", "ZN"}


def records(lines):
    """Yield (section, [lines]) per species between 'thermo' and END REACTANTS."""
    i = next(k for k, l in enumerate(lines) if l.startswith("thermo")) + 2
    section = "PRODUCTS"
    while i < len(lines):
        line = lines[i]
        if line.startswith("END PRODUCTS"):
            section = "REACTANTS"
            i += 1
            continue
        if line.startswith("END REACTANTS"):
            return
        if line.startswith("!") or not line.strip():
            i += 1
            continue
        head = lines[i + 1]
        n = int(head[0:2])
        count = 2 + (3 * n if n > 0 else 1)
        yield section, lines[i:i + count]
        i += count


def elements(rec):
    head = rec[1]
    out = set()
    for k in range(5):
        sym = head[10 + 8 * k:12 + 8 * k].strip().upper()
        cnt = float(head[12 + 8 * k:18 + 8 * k] or 0)
        if sym and cnt != 0:
            out.add(sym)
    return out


def main(path):
    with open(path, encoding="latin-1") as f:
        lines = [l.rstrip("\r\n") for l in f]
    out = ["! Subset of the NASA Glenn thermodynamic database (NASA/TP-2002-211556)",
           "! as distributed with NASA CEA. Generated by scripts/build-thermo-subset.py.",
           "! Elements kept: " + " ".join(sorted(KEEP)) + "; ions dropped.",
           "thermo",
           "    200.00   1000.00   6000.00  20000.     9/09/04"]
    kept = {"PRODUCTS": 0, "REACTANTS": 0}
    current = "PRODUCTS"
    for section, rec in records(lines):
        if section != current:
            out.append("END PRODUCTS")
            current = section
        el = elements(rec)
        if "E" in el or not el <= KEEP:
            continue
        out.extend(rec)
        kept[section] += 1
    if current == "PRODUCTS":
        out.append("END PRODUCTS")
    out.append("END REACTANTS")
    dest = "crates/astraea-core/data/thermo-propellant.inp"
    with open(dest, "w", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(dest, kept)


if __name__ == "__main__":
    main(sys.argv[1])
