"""Emit the raw thrust-curve samples the round-2 notebooks use, verbatim.

Usage: python3 -I gen_motors.py <inputs-dir> <out.ts>
Reads RocketPy's data files (pinned commit, SHA-256 in the protocol) and writes
[time s, thrust N] pairs exactly as in the files. All processing (clipping,
reshaping, zero anchors) happens in motors.ts, in the open. For .eng files the
first non-comment line is the header and is skipped, as RocketPy's import_eng does.
"""
import os
import re
import sys

SOURCES = [
    ('k828fj', 'motors/AeroTech_K828FJ.eng', 'RocketPy data/motors/aerotech/AeroTech_K828FJ.eng'),
    ('k650', 'motors/Cesaroni_1997K650-21A.eng', 'RocketPy data/motors/cesaroni/Cesaroni_1997K650-21A.eng'),
    ('l995', 'motors/Cesaroni_3618L995-P.eng', 'RocketPy data/motors/cesaroni/Cesaroni_3618L995-P.eng'),
    ('l1350', 'motors/Cesaroni_4263L1350-P.eng', 'RocketPy data/motors/cesaroni/Cesaroni_4263L1350-P.eng'),
    ('m1520', 'motors/Cesaroni_7579M1520-P.eng', 'RocketPy data/motors/cesaroni/Cesaroni_7579M1520-P.eng'),
    ('m1101', 'motors/Cesaroni_M1101.eng', 'RocketPy data/motors/cesaroni/Cesaroni_M1101.eng'),
    ('andromeda', 'thrust/andromeda_thrust_curve.csv', 'RocketPy data/rockets/andromeda/thrust_curve.csv'),
    ('erebus11', 'thrust/erebus11_thrust_source.csv', 'RocketPy data/rockets/erebus11/thrust_source.csv'),
    ('mandioca', 'thrust/juno3_mandioca_thrust_curve.csv', 'RocketPy data/motors/projeto-jupiter/mandioca_thrust_curve.csv'),
]


def load(path):
    pts = []
    header_seen = not path.endswith('.eng')
    with open(path, encoding='utf-8-sig') as fh:
        for line in fh:
            line = re.sub(r';.*', '', line)
            if not line.strip():
                continue
            if not header_seen:
                header_seen = True
                continue
            t, f = re.findall(r'[-+]?\d*\.\d+|[-+]?\d+', line)[:2]
            pts.append((float(t), float(f)))
    return pts


def main(root, out):
    lines = [
        '/**',
        ' * Thrust samples used by the round-2 validation notebooks, copied verbatim from',
        ' * RocketPy (MIT) data files at commit 9bd6ad3a. Generated by',
        ' * scripts/round2/gen_motors.py; do not hand-edit.',
        ' */',
        'export type RawCurve = ReadonlyArray<readonly [number, number]>;',
        '',
    ]
    for key, rel, src in SOURCES:
        pts = load(os.path.join(root, rel))
        lines.append(f'/** {src} */')
        lines.append(f'export const RAW_{key.upper()}: RawCurve = [')
        row = []
        for t, f in pts:
            row.append(f'[{t!r}, {f!r}]')
            if len(row) == 6:
                lines.append('  ' + ', '.join(row) + ',')
                row = []
        if row:
            lines.append('  ' + ', '.join(row) + ',')
        lines.append('];')
        lines.append('')
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
