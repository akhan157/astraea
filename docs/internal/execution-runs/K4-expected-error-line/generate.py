import argparse, json, statistics, hashlib
from pathlib import Path
parser = argparse.ArgumentParser()
parser.add_argument('manifest', type=Path)
parser.add_argument('cohort', type=Path)
parser.add_argument('output', type=Path)
parser.add_argument('--option', choices=['mae', 'maximum'], default='mae')
args = parser.parse_args()
manifest, cohort, output = args.manifest, args.cohort, args.output
assert hashlib.sha256(manifest.read_bytes()).hexdigest() == '3bd280773404b406439dd4684ad0d5a7f484a8fd7e9f61aaf237b2afd1fe54f5'
m = json.loads(manifest.read_text())['entries']; c = json.loads(cohort.read_text())
assert c['wasm_sha256'] == '4c1ec4ed7192f0f0eab9206481e74d2627c3a2f8010376a69f9194df10824535'  # goal-path WASM after the E1 merge; rows byte-identical to bc19590b (step3-e1)
r = {x['slug']:x for x in c['rows']}
groups = {'subsonic':'byrum calisp1 calisp2 calisp3 cancerdescending ezi65 gibb thunder-lightning', 'transonic':'blister calisp4 calisp5 iondrive rabia raven torrent', 'supersonic':'dontdebatethis full-metal-jacket kinsel l500roc proteus6'}
values = {}
for name, names in groups.items():
 errors=[]
 for n in names.split():
  flights=[e for e in m if e['airframe_group']==n]
  errors.append(abs(statistics.median((r[e['slug']]['cand']['apogeeAltitude']-e['measured_altitude_m'])/e['measured_altitude_m']*100 for e in flights)))
 values[name]={'airframes':len(names.split()),'mae':statistics.mean(errors),'maximum':max(errors)}
allnames=set(' '.join(groups.values()).split()); flights=[e for e in m if e['airframe_group'] in allnames]
values['maxMach']=max(r[e['slug']]['cand']['maxMach'] for e in flights)
values['maxApogee']=max(r[e['slug']]['cand']['apogeeAltitude'] for e in flights)
output.write_text('// Generated by docs/internal/execution-runs/K4-expected-error-line/generate.py; do not edit values.\nexport const cohortError = '+json.dumps(values,indent=2)+' as const;\n\n// Switch here for owner review.\nexport const cohortErrorOption: \'mae\' | \'maximum\' = \''+args.option+'\';\n')
