//! Frozen cross-language fixture for the published supersonic normal law.
//!
//! Run with ASTRAEA_P1_WRITE_FIXTURE=1 to regenerate; the default run verifies
//! the committed fixture against the Rust law. The TypeScript test
//! `src/dynamics/publishedNormal.fixture.test.ts` reads the same file, so the
//! two mirrors are held to <=1e-12 relative agreement.

use astraea_core::six_dof::{
    flight_normal_at_mach, BoattailLift, FinNormalSet, SupersonicNormal, Vehicle,
};
use serde_json::{json, Value};

fn params(kind: usize, boattail: BoattailLift) -> SupersonicNormal {
    let (sets, pos_cna, pos_cp, att_cna, att_cp) = match kind {
        0 => (
            vec![
                FinNormalSet { cna_per_rad: 7.0, cp_station_m: 3.5, aspect_ratio: 1.5, leading_edge_cos: 0.8 },
                FinNormalSet { cna_per_rad: 1.2, cp_station_m: 2.1, aspect_ratio: 2.4, leading_edge_cos: 0.95 },
            ],
            2.0,
            0.8,
            1.2,
            -0.5,
        ),
        1 => (
            vec![FinNormalSet { cna_per_rad: 11.0, cp_station_m: 2.3, aspect_ratio: 2.74, leading_edge_cos: 0.79 }],
            2.0,
            0.48,
            2.0,
            0.48,
        ),
        _ => (
            vec![FinNormalSet { cna_per_rad: 4.0, cp_station_m: 1.1, aspect_ratio: 0.9, leading_edge_cos: 0.45 }],
            1.6,
            0.6,
            0.9,
            -1.0,
        ),
    };
    SupersonicNormal {
        fin_sets: sets,
        body_positive_cna: pos_cna,
        body_positive_moment: pos_cna * pos_cp,
        body_positive_abs_cna: pos_cna,
        body_attached_cna: att_cna,
        body_attached_moment: att_cna * att_cp,
        body_attached_abs_cna: att_cna.abs(),
        boattail_lift: boattail,
    }
}

fn vehicle(p: &SupersonicNormal) -> Vehicle {
    let mut v = astraea_core::six_dof::estes_alpha_vehicle();
    v.cna_body = p.body_attached_cna;
    v.body_first_moment = p.body_attached_moment;
    v.body_abs_cna = p.body_attached_abs_cna;
    v.cna_fins = p.fin_sets.iter().map(|s| s.cna_per_rad).sum();
    v.fin_first_moment = p.fin_sets.iter().map(|s| s.cna_per_rad * s.cp_station_m).sum();
    v.fin_abs_cna = p.fin_sets.iter().map(|s| s.cna_per_rad.abs()).sum();
    v.supersonic_normal = Some(p.clone());
    v
}

fn params_json(p: &SupersonicNormal) -> Value {
    json!({
        "finSets": p.fin_sets.iter().map(|s| json!({
            "cna": s.cna_per_rad,
            "cp": s.cp_station_m,
            "aspectRatio": s.aspect_ratio,
            "leadingEdgeCos": s.leading_edge_cos,
        })).collect::<Vec<_>>(),
        "bodyPositiveCna": p.body_positive_cna,
        "bodyPositiveMoment": p.body_positive_moment,
        "bodyPositiveAbsCna": p.body_positive_abs_cna,
        "bodyAttachedCna": p.body_attached_cna,
        "bodyAttachedMoment": p.body_attached_moment,
        "bodyAttachedAbsCna": p.body_attached_abs_cna,
        "boattailLift": if p.boattail_lift == BoattailLift::Attached { "attached" } else { "suppressed" },
    })
}

#[test]
fn frozen_cross_language_fixture_matches_the_rust_law() {
    let machs = [0.4, 0.79, 0.8, 0.9000000000000001, 1.0, 1.1000000000000001, 1.2, 1.5, 2.0, 2.96, 4.0];
    let mut cases = Vec::new();
    for kind in 0..3 {
        for boattail in [BoattailLift::Suppressed, BoattailLift::Attached] {
            let p = params(kind, boattail);
            let v = vehicle(&p);
            for &mach in &machs {
                let (cna, cp, moment) = flight_normal_at_mach(mach, &v).expect("law");
                cases.push(json!({
                    "mach": mach,
                    "params": params_json(&p),
                    "expected": {"cna": cna, "cp": cp, "moment": moment},
                }));
            }
        }
    }
    let document = json!({
        "law": "published-supersonic-normal-v1",
        "note": "generated by crates/astraea-engine/tests/p1_normal_fixture.rs; TS mirror must match to 1e-12 relative",
        "cases": cases,
    });
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../src/dynamics/p1_normal_fixture.json");
    if std::env::var("ASTRAEA_P1_WRITE_FIXTURE").is_ok() {
        std::fs::write(&path, serde_json::to_string_pretty(&document).unwrap()).unwrap();
        println!("wrote {}", path.display());
        return;
    }
    let committed: Value =
        serde_json::from_str(&std::fs::read_to_string(&path).expect("committed fixture")).unwrap();
    // serde_json's default float parser may lose one ULP on read; compare the
    // scientific values, not the JSON token identities.
    let committed_cases = committed["cases"].as_array().expect("cases");
    assert_eq!(committed_cases.len(), cases.len(), "fixture case count");
    for (got, want) in committed_cases.iter().zip(cases.iter()) {
        for key in ["cna", "cp", "moment"] {
            let a = got["expected"][key].as_f64().expect("number");
            let b = want["expected"][key].as_f64().expect("number");
            let tol = 1e-15 * b.abs().max(1.0);
            assert!(
                (a - b).abs() <= tol,
                "fixture drift at M{} {key}: {a:.17e} vs {b:.17e}",
                got["mach"]
            );
        }
    }
}
